            $agentId = $row['agent_slug'] ? ($agentsBySlug[$row['agent_slug']] ?? null) : null;
            $companyId = $row['company_slug'] ? ($companiesBySlug[$row['company_slug']] ?? null) : null;

            unset($row['category_slug'], $row['city_slug'], $row['agent_slug'], $row['company_slug']);

            $userID = null;
            $agent = Agent::find($agentId);
            $userID = $agent->user_id;

            if(!$userID){
                $comp = Company::find($companyId);
                $userID = $comp->user_id;
            }


            Property::updateOrCreate(
                ['slug' => $row['slug']],
                [
                    ...$row,
                    'category_id' => $categoryId,
                    'city_id' => $cityId,
                    'user_id' => $userID,
                    'agent_id' => $agentId,
                    'company_id' => $companyId,
                ]
            );
        }
    }
